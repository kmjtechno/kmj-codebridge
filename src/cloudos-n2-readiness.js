  "        st=os.lstat('/dev/kvm')",
  "        if not stat.S_ISCHR(st.st_mode):",
  "            return 'NOT_CHARACTER_DEVICE'",
  "        fd=os.open('/dev/kvm',os.O_RDWR|os.O_CLOEXEC|os.O_NOFOLLOW)",
  "        try:",
  "            return 'ABI_12_USABLE' if fcntl.ioctl(fd,0xAE00,0)==12 else 'ABI_NOT_12'",
